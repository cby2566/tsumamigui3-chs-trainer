def width(op: int) -> int:
    """指令字节宽度，未知 opcode 返回 0。"""
    e = OPCODES.get(op)
    return 2 + 4 * e[1] if e else 0


def name(op: int) -> str:
    e = OPCODES.get(op)
    return e[0] if e else f"UNKNOWN_0x{op:04X}"
